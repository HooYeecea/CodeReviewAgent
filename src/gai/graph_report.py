def graph_report_path(cwd: Path | None = None) -> Path:
    return project_root(cwd) / _GRAPH_HTML_RELATIVE


def graph_data_path(cwd: Path | None = None) -> Path:
    return project_root(cwd) / _GRAPH_DATA_RELATIVE


